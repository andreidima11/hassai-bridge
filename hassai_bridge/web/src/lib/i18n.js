export function readStoredLang() {
  try {
    const stored = localStorage.getItem(LANG_STORE_KEY);
    if (stored === "ro" || stored === "en") return stored;
  } catch {
    /* ignore */
  }
  return "en";
}

export function persistLang(next) {
  try {
    localStorage.setItem(LANG_STORE_KEY, next);
  } catch {
    /* ignore */
  }
}

export function tr(lang, key, params = {}) {
  const table = I18N[lang] || I18N.en;
  let str = table[key] || I18N.en[key] || key;
  for (const [k, v] of Object.entries(params)) str = str.replaceAll(`{${k}}`, v);
  return str;
}

/** Localized label for a Settings tool group (`ha:entities`, `bridge:browser`, …). */
export function toolGroupLabel(lang, groupKey) {
  const raw = String(groupKey || "").trim();
  if (!raw) return "";
  const [ns, id] = raw.includes(":") ? raw.split(":", 2) : ["", raw];
  const short = id || raw;
  // HA "control" shares the short id with bridge control — disambiguate.
  const key =
    ns === "ha" && short === "control"
      ? "toolGroup_ha_control"
      : `toolGroup_${short}`;
  const translated = tr(lang, key);
  return translated === key ? short : translated;
}

/** Localized Approve-card body from enable_group + optional reason. */
export function enableApprovalPreview(lang, groupKey, reason = "") {
  const short = String(groupKey || "").includes(":")
    ? String(groupKey).split(":", 2)[1]
    : String(groupKey || "").trim();
  if (!short) return String(reason || "").trim();
  const bits = [tr(lang, "enablePreview", { id: short })];
  const label = toolGroupLabel(lang, groupKey);
  if (label) bits.push(label);
  const why = String(reason || "").trim();
  if (why) bits.push(why.slice(0, 160));
  return bits.join(" · ");
}

export function activityVerb(lang, name) {
  if (name === "think") return tr(lang, "thinking");
  if (name === "say") return tr(lang, "saidStep");
  const translated = tr(lang, name);
  return translated === name ? name.replace(/^ha_/, "").replace(/_/g, " ") : translated;
}

export function liveThinkingLabel(lang, thinking) {
  const awaiting = (thinking.steps || []).find((step) => step.status === "awaiting_approval");
  if (awaiting) return tr(lang, "approvalWaiting");
  const runningTool = (thinking.steps || []).find((step) => step.status === "running" && step.name !== "think");
  if (runningTool) {
    const verb = activityVerb(lang, runningTool.name);
    const detail = String(runningTool.detail || "").trim();
    if (detail) return `${verb} · ${detail}`;
    return `${verb}…`;
  }
  const runningThink = (thinking.steps || []).find((step) => step.status === "running" && step.name === "think");
  if (runningThink || thinking.active) return tr(lang, "thinkingLive");
  return thinking.label || tr(lang, "thoughtBrief");
}

/** Prefer result outcome when done; otherwise args preview. */
export function stepDisplayDetail(step) {
  const done = step?.status === "done" || step?.status === "skip";
  const result = String(step?.result_preview || "").trim();
  if (done && result) return result;
  return String(step?.detail || step?.args_preview || "").trim();
}

export function formatMs(ms) {
  const n = Number(ms);
  if (!Number.isFinite(n) || n < 0) return "";
  if (n < 1000) return `${Math.round(n)}ms`;
  return `${(n / 1000).toFixed(n >= 10000 ? 0 : 1)}s`;
}

export function finishThinkingLabel(lang, thinking) {
  const tools = (thinking.steps || []).filter((s) => s.name !== "think");
  const thinkMs = Number(thinking.thinkMs || 0);
  let toolMs = 0;
  for (const s of tools) {
    const t = formatMs(s.ms);
    if (t.endsWith("ms")) toolMs += parseFloat(t) || 0;
    else if (t.endsWith("s")) toolMs += (parseFloat(t) || 0) * 1000;
  }
  const totalMs = Math.max(thinkMs + toolMs, thinkMs, toolMs);
  if (!tools.length && thinkMs <= 0) return "";
  if (tools.length) {
    return tr(lang, "steps", {
      n: tools.length,
      s: (totalMs / 1000).toFixed(totalMs >= 10000 ? 0 : 1),
    });
  }
  return thinkMs >= 1000
    ? tr(lang, "thoughtFor", { s: (thinkMs / 1000).toFixed(thinkMs >= 10000 ? 0 : 1) })
    : tr(lang, "thoughtBrief");
}
